-- Actual Win64 API, only Lua-owned buffers in this private test process.
local ROOT=assert(arg[1])
local ffi=require('ffi')
local Runtime=dofile(ROOT..'/vendor/shared/bingus_runtime.lua')
local memory=dofile(ROOT..'/vendor/shared/bingus_memory.lua').new(Runtime)
local writer=dofile(ROOT..'/src/data_writer.lua').new(memory)
local storage=ffi.new('uint8_t[64]');ffi.fill(storage,64,0x5a)
local address=memory.address(storage)
address=address+(8-address%8)%8
local expected=memory.read(ffi.cast('uint8_t *',address),8)
local desired=string.char(1,2,3,4,5,6,7,8)
assert(writer.replace(address,expected,desired,function()return true end))
assert(writer.writes==1 and memory.read(ffi.cast('uint8_t *',address),8)==desired)
assert(ffi.string(storage+16,48)==string.rep('Z',48),'write crossed eight-byte boundary')
assert(not writer.replace(address,desired,expected,function()return false end))
assert(not writer.replace(address+1,desired,expected,function()error('unaligned validation ran')end))
assert(not writer.replace(0,desired,expected,function()error('null validation ran')end))
assert(not writer.replace(address,desired,expected:sub(1,7),function()return true end))
assert(not writer.replace(address,desired,desired,function()error('unchanged validation ran')end))
assert(not writer.replace(address,expected,desired,function()return true end))
assert(not writer.replace(0x70000000,desired,expected,function()error('unmapped validation ran')end))
assert(not writer.replace(address,desired,expected,function()
    ffi.fill(ffi.cast('void *',address),8,0x33);return true
end),'changed expected selection overwritten')
assert(writer.writes==1)
-- Module images and executable pages must be refused without opening protection.
local module=memory.address(memory.module(nil))
assert(not writer.replace(module,string.rep('\0',8),desired,function()error('image validation ran')end))
print('PASS actual Win64 data writer: one private-buffer write, nine refusals, image/unmapped/alignment/race guards; no game process')
